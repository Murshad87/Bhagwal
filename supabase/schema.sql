create table if not exists public.notices (
  id bigint generated by default as identity primary key,
  title text not null,
  description text not null,
  category text not null default 'Notice',
  author_name text,
  contact_phone text,
  status text not null default 'approved' check (status in ('pending', 'approved')),
  created_at timestamptz not null default now()
);

create table if not exists public.businesses (
  id bigint generated by default as identity primary key,
  name_urdu text,
  name_eng text not null,
  category text not null,
  tags text[] not null default '{}',
  phone text,
  location text,
  is_active boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists public.gallery_photos (
  id bigint generated by default as identity primary key,
  title text not null,
  description text,
  image_url text not null,
  is_published boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists public.admin_profiles (
  user_id uuid primary key references auth.users(id) on delete cascade,
  role text not null default 'admin' check (role = 'admin'),
  created_at timestamptz not null default now()
);

alter table public.notices enable row level security;
alter table public.businesses enable row level security;
alter table public.gallery_photos enable row level security;
alter table public.admin_profiles enable row level security;

create or replace function public.is_admin()
returns boolean
language sql
security definer
set search_path = public
as $$
  select exists (
    select 1
    from public.admin_profiles
    where user_id = auth.uid()
      and role = 'admin'
  );
$$;

revoke all on function public.is_admin() from public;
grant execute on function public.is_admin() to authenticated;

create policy "Public reads approved notices"
  on public.notices for select
  to anon, authenticated
  using (status = 'approved');

create policy "Admins read all notices"
  on public.notices for select
  to authenticated
  using (public.is_admin());

create policy "Admins publish notices"
  on public.notices for insert
  to authenticated
  with check (public.is_admin() and status = 'approved');

create policy "Admins update notices"
  on public.notices for update
  to authenticated
  using (public.is_admin())
  with check (public.is_admin());

create policy "Admins delete notices"
  on public.notices for delete
  to authenticated
  using (public.is_admin());

create policy "Public reads active businesses"
  on public.businesses for select
  to anon, authenticated
  using (is_active = true);

create policy "Admins manage businesses"
  on public.businesses for all
  to authenticated
  using (public.is_admin())
  with check (public.is_admin());

create policy "Public reads published photos"
  on public.gallery_photos for select
  to anon, authenticated
  using (is_published = true);

create policy "Admins manage photos"
  on public.gallery_photos for all
  to authenticated
  using (public.is_admin())
  with check (public.is_admin());

create policy "Admins read own profile"
  on public.admin_profiles for select
  to authenticated
  using (user_id = auth.uid());

insert into storage.buckets (id, name, public)
values ('gallery', 'gallery', true)
on conflict (id) do update set public = excluded.public;

create policy "Public reads gallery images"
  on storage.objects for select
  to anon, authenticated
  using (bucket_id = 'gallery');

create policy "Admins upload gallery images"
  on storage.objects for insert
  to authenticated
  with check (bucket_id = 'gallery' and public.is_admin());

create policy "Admins update gallery images"
  on storage.objects for update
  to authenticated
  using (bucket_id = 'gallery' and public.is_admin())
  with check (bucket_id = 'gallery' and public.is_admin());

create policy "Admins delete gallery images"
  on storage.objects for delete
  to authenticated
  using (bucket_id = 'gallery' and public.is_admin());
